import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { chapters, slides } from "./content.mjs";

const here = dirname(fileURLToPath(import.meta.url));
const revision = resolve(here, "..");
const player = resolve(revision, "player");
const rootFromPlayer = "../../../../../../";
const deck = slides.map((slide, index) => ({
  index: index + 1,
  chapter: chapters.find((chapter) => index >= chapter.start && index < chapter.end)?.id,
  title: slide.title.replaceAll("\n", " "),
  subtitle: slide.subtitle ?? "",
  image: `../${slide.slug}/slide.svg`,
  narration: slide.narration,
  links: [...(slide.codeLinks ?? []), ...(slide.extraLinks ?? [])].map(([label, href]) => ({
    label,
    href: `${rootFromPlayer}${href}`,
  })),
}));

await mkdir(player, { recursive: true });
const template = await readFile(resolve(player, "app.template.js"), "utf8");
await writeFile(
  resolve(player, "app.js"),
  `// Generated by tools/build-player.mjs. Do not edit this file directly.\nconst WALKTHROUGH = ${JSON.stringify({ chapters, slides: deck }, null, 2)};\n\n${template}`,
  "utf8",
);
console.log(`Built narrated player with ${deck.length} slides at ${player}`);
